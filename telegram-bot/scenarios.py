# \b спереди требует начала слова: «цена» — это prices, «оценка» — нет.
_PATTERNS = {key: re.compile(r"\b(?:" + "|".join(words) + r")") for key, words in KEYWORDS.items()}


def match(text: str) -> str | None:
    """Ключ готового ответа для текста клиента или None — тогда спрашиваем backend.

    Совпали сразу две темы — не гадаем, уводим вопрос в RAG.
    """
    lowered = text.lower()
    hits = [key for key, pattern in _PATTERNS.items() if pattern.search(lowered)]
    return hits[0] if len(hits) == 1 else None


def answer_for(key: str) -> str | None:
    """Текст по ключу кнопки или None, если такой кнопки нет."""
    return ANSWERS.get(key)
